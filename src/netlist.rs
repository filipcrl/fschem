//! Static Xschem SPICE and native VACASK netlisting. Shared schematic connectivity.
use crate::{
    document::{Document, Properties, RecordKind},
    geometry::{Bounds, Point, Transform},
    library::{Library, LibraryPaths},
    navigation::{self, Descent, DocumentTarget},
    scene::InstanceInfo,
};
use std::{
    collections::{HashMap, HashSet},
    path::{Path, PathBuf},
    sync::Arc,
};

/// Generate a complete SPICE deck, including reachable subcircuit definitions.
/// Errors are returned before any output is written; unsupported dynamic constructs
/// must not silently produce a different circuit.
pub fn spice(document: &Document, source: &Path, paths: LibraryPaths) -> Result<String, String> {
    let mut exporter = Exporter {
        library: Library::new(paths),
        active: HashSet::new(),
        definitions: HashMap::new(),
        models: HashSet::new(),
        trailer: String::new(),
        vacask: false,
    };
    let body = exporter.sheet(document, source, None, 0)?;
    // User code blocks often include .end. Keep it after generated model and
    // hierarchy definitions, rather than terminating the deck before them.
    let content = format!("{body}{}", exporter.trailer);
    let content = content
        .lines()
        .filter(|line| !line.trim().eq_ignore_ascii_case(".end"))
        .map(|line| format!("{line}\n"))
        .collect::<String>();
    Ok(format!(
        "* {} (generated by fschem)\n{content}.end\n",
        source.display(),
    ))
}

/// Generate native VACASK syntax. Testbench code is native, never translated
/// from SPICE. Connectivity and hierarchy traversal are shared with SPICE.
pub fn vacask(document: &Document, source: &Path, paths: LibraryPaths) -> Result<String, String> {
    let mut exporter = Exporter {
        library: Library::new(paths),
        active: HashSet::new(),
        definitions: HashMap::new(),
        models: HashSet::new(),
        trailer: String::new(),
        vacask: true,
    };
    let body = exporter.sheet(document, source, None, 0)?;
    Ok(format!(
        "{} (generated by fschem)\n{body}{}",
        source.display(),
        exporter.trailer
    ))
}

/// Write a generated deck, refusing schematic/symbol destinations.
pub fn write_spice(path: &Path, deck: &str) -> Result<(), String> {
    let target = std::fs::canonicalize(path).unwrap_or_else(|_| path.to_owned());
    if [path, target.as_path()].iter().any(|p| {
        p.extension()
            .is_some_and(|e| e.eq_ignore_ascii_case("sch") || e.eq_ignore_ascii_case("sym"))
    }) {
        return Err(
            "Choose a netlist destination (.spice, .sp or .cir), not a schematic/symbol file"
                .into(),
        );
    }
    std::fs::write(path, deck).map_err(|e| format!("{}: {e}", path.display()))
}

struct Component {
    info: InstanceInfo,
    metadata: Properties,
    defaults: Properties,
    pins: Vec<(usize, Properties)>,
    line: usize,
}
impl Component {
    fn value(&self, key: &str) -> Option<&str> {
        self.info
            .properties
            .get(key)
            .or_else(|| self.defaults.get(key))
            .or_else(|| self.metadata.get(key))
    }
    fn kind(&self) -> &str {
        self.metadata.get("type").unwrap_or("")
    }
    fn flag(&self, key: &str) -> bool {
        self.value(key)
            .is_some_and(|v| matches!(v, "true" | "1" | "yes" | "on"))
    }
    fn symname(&self) -> String {
        Path::new(&self.info.symbol)
            .file_stem()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned()
    }
}

struct Exporter {
    library: Library,
    active: HashSet<PathBuf>,
    definitions: HashMap<String, PathBuf>,
    models: HashSet<String>,
    trailer: String,
    vacask: bool,
}
impl Exporter {
    fn vacask_component(&mut self, c: &Component, nets: &[String]) -> Result<String, String> {
        let name = c.value("name").unwrap_or("?");
        let native = if let Some(format) = c.value("vacask_format") {
            expand(format, c, nets)?
        } else if c.kind() == "netlist_commands" {
            c.value("vacask_code")
                .or_else(|| c.value("value"))
                .ok_or_else(|| format!("{name}: missing VACASK testbench code"))?
                .to_owned()
        } else {
            let pins = c
                .pins
                .iter()
                .map(|(i, _)| nets[*i].as_str())
                .collect::<Vec<_>>()
                .join(" ");
            let (device, parameter, module) = match c.kind() {
                "resistor" => ("resistor", "r", Some("resistor.osdi")),
                "capacitor" => ("capacitor", "c", Some("capacitor.osdi")),
                "inductor" => ("inductor", "l", Some("inductor.osdi")),
                "vsource" => ("vsource", "dc", None),
                "isource" => ("isource", "dc", None),
                _ => {
                    return Err(format!(
                        "line {} ({name}): add vacask_format to this symbol/instance; no native mapping for {:?}",
                        c.line,
                        c.kind()
                    ));
                }
            };
            if c.pins.len() != 2 {
                return Err(format!("{name}: native {device} requires two pins"));
            }
            if c.value("device_model").is_some_and(|v| !v.is_empty()) {
                return Err(format!(
                    "{name}: SPICE device_model cannot be used with the default VACASK mapping; supply vacask_format and vacask_model"
                ));
            }
            let model = format!("fschem_{device}");
            let declaration = format!(
                "{}model {model} {device}",
                module
                    .map(|m| format!("load \"{m}\"\n"))
                    .unwrap_or_default()
            );
            if self.models.insert(declaration.clone()) {
                append(&mut self.trailer, &declaration);
            }
            let params = if let Some(params) = c.value("vacask_params") {
                params.to_owned()
            } else {
                let value = c.value("value").ok_or_else(|| {
                    format!("{name}: missing value; use native vacask_params or vacask_format")
                })?;
                // Never reinterpret a SPICE source waveform as native syntax.
                if value.contains(char::is_whitespace) || value.contains(['(', ')', '{', '}']) {
                    return Err(format!(
                        "{name}: use vacask_params for native source/parameter expressions, not a SPICE value"
                    ));
                }
                format!("{parameter}={value}")
            };
            format!("{name} ({pins}) {model} {params}")
        };
        if native
            .lines()
            .any(|line| line.trim_start().starts_with('.'))
        {
            return Err(format!(
                "{name}: SPICE directives are not VACASK syntax; use a native control/endc block with analysis commands (or set vacask_code)"
            ));
        }
        Ok(native)
    }

    fn sheet(
        &mut self,
        doc: &Document,
        source: &Path,
        ports: Option<&[String]>,
        depth: usize,
    ) -> Result<String, String> {
        self.sheet_inner(doc, source, ports, depth)
            .map_err(|e| format!("{}: {e}", source.display()))
    }
    fn sheet_inner(
        &mut self,
        doc: &Document,
        source: &Path,
        ports: Option<&[String]>,
        depth: usize,
    ) -> Result<String, String> {
        if depth > 32 {
            return Err("subcircuit hierarchy exceeds 32 levels".into());
        }
        let ResolvedSheet {
            components,
            pin_names,
        } = resolve_sheet(&mut self.library, doc, source, ports, Some(self.vacask))?;
        let mut output = String::new();
        // Xschem's E block is the Spectre/native deck preamble; S is SPICE.
        if let Some(global) = doc.global(if self.vacask { 'E' } else { 'S' }) {
            append(&mut output, &global.raw);
        }
        let mut used_names = HashSet::new();
        for c in &components {
            if is_label(c.kind()) || c.kind() == "noconn" {
                continue;
            }
            if depth > 0 && c.flag("only_toplevel") {
                continue;
            }
            if !self.vacask && depth > 0 && c.flag("savecurrent") {
                return Err("savecurrent within subcircuits is not yet supported".into());
            }
            let name = c
                .value("name")
                .ok_or_else(|| format!("line {}: missing instance name", c.line))?;
            scalar(name)?;
            if !used_names.insert(name.to_ascii_lowercase()) {
                return Err(format!("duplicate instance name {name:?}"));
            }
            let line = if self.vacask {
                self.vacask_component(c, &pin_names)?
            } else {
                let format = c.value("format").ok_or_else(|| {
                    format!("line {} ({name}): symbol has no SPICE format", c.line)
                })?;
                expand(format, c, &pin_names)
                    .map_err(|e| format!("line {} ({name}): {e}", c.line))?
            };
            if c.flag("spice_short") {
                return Err(format!("{name}: spice_short is not supported"));
            }
            if let Some(model) = c
                .value(if self.vacask {
                    "vacask_model"
                } else {
                    "device_model"
                })
                .filter(|v| !v.is_empty())
            {
                let model = expand(model, c, &pin_names)?;
                if self.models.insert(model.clone()) {
                    append(&mut self.trailer, &model);
                }
            }
            append(&mut output, &line);
            if c.kind() == "subcircuit"
                && !c.flag(if self.vacask {
                    "vacask_stop"
                } else {
                    "spice_stop"
                })
            {
                let subname = c.symname();
                scalar(&subname)?;
                let DocumentTarget::File(path) =
                    navigation::descend(&c.info, Descent::Schematic, &self.library.paths)?
                else {
                    unreachable!()
                };
                if self.active.contains(&path) {
                    return Err(format!("recursive subcircuit {}", path.display()));
                }
                if let Some(previous) = self.definitions.get(&subname.to_ascii_lowercase()) {
                    if previous != &path {
                        return Err(format!(
                            "different schematics use subcircuit name {subname}"
                        ));
                    }
                    continue;
                }
                let ports: Vec<_> = c
                    .pins
                    .iter()
                    .map(|(_, p)| {
                        p.get("name")
                            .ok_or_else(|| "subcircuit pin has no name".to_owned())
                            .and_then(scalar)
                            .map(str::to_owned)
                    })
                    .collect::<Result<_, _>>()?;
                self.definitions
                    .insert(subname.to_ascii_lowercase(), path.clone());
                self.active.insert(path.clone());
                let child = self.library.document(&path)?;
                let body = self.sheet(&child, &path, Some(&ports), depth + 1)?;
                self.active.remove(&path);
                let parameters = c
                    .metadata
                    .get("template")
                    .map(|t| Properties::parse(t.into()))
                    .unwrap_or_default();
                let params = parameters
                    .entries
                    .iter()
                    .filter(|(key, _)| key != "name")
                    .filter_map(|(key, value)| value.as_ref().map(|v| format!(" {key}={v}")))
                    .collect::<String>();
                let definition = if self.vacask {
                    let params = if params.is_empty() {
                        String::new()
                    } else {
                        format!("parameters{params}\n")
                    };
                    format!(
                        "subckt {subname} ({})\n{params}{body}ends\n",
                        ports.join(" ")
                    )
                } else {
                    format!(
                        ".subckt {subname} {}{params}\n{body}.ends {subname}",
                        ports.join(" ")
                    )
                };
                append(&mut self.trailer, &definition);
            }
        }
        Ok(output)
    }
}

fn is_label(kind: &str) -> bool {
    matches!(kind, "label" | "ipin" | "opin" | "iopin")
}
fn append(output: &mut String, text: &str) {
    if !text.trim().is_empty() {
        output.push_str(text);
        if !text.ends_with('\n') {
            output.push('\n');
        }
    }
}
fn scalar(value: &str) -> Result<&str, String> {
    if value.is_empty()
        || value.chars().any(char::is_whitespace)
        || value.contains([',', ':', '*', '@'])
        || value.contains("tcleval(")
    {
        Err(format!(
            "unsupported scalar name {value:?}; bus/vector and dynamic names are not yet supported"
        ))
    } else {
        Ok(value)
    }
}
fn expand(format: &str, c: &Component, nets: &[String]) -> Result<String, String> {
    if format.contains("tcleval(") || format.contains("@tcl") {
        return Err("Tcl netlist expressions are not supported".into());
    }
    let mut result = String::new();
    let mut chars = format.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch != '@' {
            result.push(ch);
            continue;
        }
        let named_pin = chars.peek() == Some(&'@');
        if named_pin {
            chars.next();
        }
        let mut key = String::new();
        while chars
            .peek()
            .is_some_and(|c| c.is_alphanumeric() || matches!(c, '_' | '#' | ':'))
        {
            key.push(chars.next().unwrap());
        }
        let value = if named_pin {
            let pin = c
                .pins
                .iter()
                .find(|(_, p)| p.get("name") == Some(&key))
                .ok_or_else(|| format!("unknown pin @@{key}"))?;
            nets[pin.0].clone()
        } else if let Some(pin) = key.strip_prefix('#') {
            let (index, attr) = pin
                .split_once(':')
                .ok_or_else(|| format!("invalid pin token @{key}"))?;
            let pin = index
                .parse::<usize>()
                .ok()
                .and_then(|i| c.pins.get(i))
                .ok_or_else(|| format!("unknown pin @{key}"))?;
            if attr == "net_name" {
                nets[pin.0].clone()
            } else {
                pin.1
                    .get(attr)
                    .ok_or_else(|| format!("missing pin attribute @{key}"))?
                    .into()
            }
        } else {
            match key.as_str() {
                "savecurrent" => {
                    if c.flag("savecurrent") {
                        format!("\n.save I({})", c.value("name").unwrap_or(""))
                    } else {
                        String::new()
                    }
                }
                "spiceprefix" | "extra" => c.value(&key).unwrap_or("").into(),
                "pinlist" => c
                    .pins
                    .iter()
                    .map(|(i, _)| nets[*i].as_str())
                    .collect::<Vec<_>>()
                    .join(" "),
                "symname" => c.symname(),
                "symname_ext" => Path::new(&c.info.symbol)
                    .file_name()
                    .unwrap_or_default()
                    .to_string_lossy()
                    .into_owned(),
                _ => c
                    .value(&key)
                    .ok_or_else(|| format!("unresolved format attribute @{key}"))?
                    .into(),
            }
        };
        if value.contains("tcleval(") {
            return Err(format!("@{key} requires Tcl evaluation"));
        }
        result.push_str(&value);
    }
    Ok(result)
}
fn bits(v: f64) -> u64 {
    if v == 0. { 0 } else { v.to_bits() }
}
fn on_segment(p: Point, a: Point, b: Point) -> bool {
    if !Bounds::new(a, b).contains(p) {
        return false;
    }
    let d = b - a;
    let q = p - a;
    (d.x * q.y - d.y * q.x).abs() <= 1e-9 * d.length().max(1.)
}
struct Nets(Vec<usize>);
impl Nets {
    fn new(n: usize) -> Self {
        Self((0..n).collect())
    }
    fn root(&mut self, mut i: usize) -> usize {
        while self.0[i] != i {
            self.0[i] = self.0[self.0[i]];
            i = self.0[i];
        }
        i
    }
    fn join(&mut self, a: usize, b: usize) {
        let a = self.root(a);
        let b = self.root(b);
        self.0[b] = a;
    }
}

/// Connectivity resolved once for native and portable lowering. Pin indices refer
/// to pin_names; symbol templates remain distinct from instance properties.
struct ResolvedSheet {
    components: Vec<Component>,
    pin_names: Vec<String>,
}
fn resolve_sheet(
    library: &mut Library,
    doc: &Document,
    source: &Path,
    ports: Option<&[String]>,
    native: Option<bool>,
) -> Result<ResolvedSheet, String> {
    if !doc.diagnostics.is_empty() {
        return Err("document has parser diagnostics; resolve them before netlisting".into());
    }
    if source
        .extension()
        .is_some_and(|e| e.eq_ignore_ascii_case("sym"))
    {
        return Err("SPICE export requires a schematic, not a symbol".into());
    }
    let mut embedded = HashMap::new();
    let mut last = None;
    for record in &doc.records {
        match &record.kind {
            RecordKind::Instance { symbol, .. } => last = Some(symbol.clone()),
            RecordKind::Embedded(records) => {
                if let Some(symbol) = &last {
                    embedded
                        .entry(symbol.clone())
                        .or_insert_with(|| Arc::new(doc.embedded(records)));
                }
            }
            _ => {}
        }
    }
    let mut points = Vec::new();
    let mut wires = Vec::new();
    let mut labels = Vec::new();
    let mut components = Vec::new();
    for record in &doc.records {
        match &record.kind {
            RecordKind::Wire { a, b, properties } => {
                let index = points.len();
                points.extend([*a, *b]);
                wires.push((index, index + 1));
                if let Some(label) = properties.get("lab") {
                    labels.push((index, scalar(label)?.to_owned()));
                }
            }
            RecordKind::Instance {
                symbol,
                at,
                rotation,
                flip,
                properties,
            } => {
                if native.is_some()
                    && properties.flag(if native == Some(true) {
                        "vacask_ignore"
                    } else {
                        "spice_ignore"
                    })
                {
                    continue;
                }
                let (definition, resolved) = if let Some(doc) = embedded.get(symbol) {
                    (Arc::clone(doc), None)
                } else {
                    let path = library
                        .paths
                        .resolve(
                            symbol,
                            source.parent().unwrap_or(Path::new(".")),
                            doc.version() == "1.0",
                        )
                        .map_err(|e| format!("line {}: {e}", record.line))?;
                    (library.document(&path)?, Some(path))
                };
                if !definition.diagnostics.is_empty() {
                    return Err(format!(
                        "line {}: symbol {symbol} has parser diagnostics",
                        record.line
                    ));
                }
                let metadata = definition.symbol_properties().cloned().unwrap_or_default();
                let defaults = Properties::parse(metadata.get("template").unwrap_or("").into());
                let mut component = Component {
                    info: InstanceInfo {
                        symbol: symbol.clone(),
                        embedded: resolved.is_none(),
                        resolved,
                        source_file: source.to_owned(),
                        definition: Some(Arc::clone(&definition)),
                        at: *at,
                        rotation: *rotation,
                        flip: *flip,
                        properties: properties.clone(),
                        bounds: Bounds::new(*at, *at),
                    },
                    metadata,
                    defaults,
                    pins: Vec::new(),
                    line: record.line,
                };
                if (native.is_some()
                    && component.flag(if native == Some(true) {
                        "vacask_ignore"
                    } else {
                        "spice_ignore"
                    }))
                    || matches!(component.kind(), "launcher" | "logo")
                    || (native.is_some() && component.kind()=="netlist_options")
                {
                    continue;
                }
                let transform = Transform::new(*at, *rotation, *flip);
                for pin in &definition.records {
                    if let RecordKind::Rectangle {
                        layer: 5,
                        a,
                        b,
                        properties,
                    } = &pin.kind
                    {
                        if native.is_none() && (properties.flag("spice_ignore") || properties.flag("vacask_ignore")) {
                            return Err(format!("line {}: backend-specific pin ignore unsupported in portable connectivity",record.line));
                        }
                        if native.is_some()
                            && properties.flag(if native == Some(true) {
                                "vacask_ignore"
                            } else {
                                "spice_ignore"
                            })
                        {
                            continue;
                        }
                        let index = points.len();
                        points.push(transform.point((*a + *b) * 0.5));
                        component.pins.push((index, properties.clone()));
                    }
                }
                if is_label(component.kind()) {
                    let label = scalar(component.value("lab").ok_or_else(|| {
                        format!("line {}: label has no lab attribute", record.line)
                    })?)?
                    .to_owned();
                    let index = component.pins.first().map(|p| p.0).unwrap_or_else(|| {
                        points.push(*at);
                        points.len() - 1
                    });
                    labels.push((index, label));
                }
                components.push(component);
            }
            _ => {}
        }
    }
    let mut nets = Nets::new(points.len());
    // Pins and wire endpoints connect to segment interiors. Two crossing
    // interiors alone do not connect (the Xschem four-way crossing rule).
    let mut positions = HashMap::new();
    for (i, point) in points.iter().enumerate() {
        let key = (bits(point.x), bits(point.y));
        if let Some(previous) = positions.insert(key, i) {
            nets.join(i, previous);
        }
    }
    let mut by_x: Vec<_> = (0..points.len()).collect();
    let mut by_y = by_x.clone();
    by_x.sort_by(|a, b| points[*a].x.total_cmp(&points[*b].x));
    by_y.sort_by(|a, b| points[*a].y.total_cmp(&points[*b].y));
    for &(a, b) in &wires {
        nets.join(a, b);
        let bounds = Bounds::new(points[a], points[b]);
        let xs = by_x.partition_point(|i| points[*i].x < bounds.min.x)
            ..by_x.partition_point(|i| points[*i].x <= bounds.max.x);
        let ys = by_y.partition_point(|i| points[*i].y < bounds.min.y)
            ..by_y.partition_point(|i| points[*i].y <= bounds.max.y);
        let candidates = if xs.len() < ys.len() {
            &by_x[xs]
        } else {
            &by_y[ys]
        };
        for &i in candidates {
            if on_segment(points[i], points[a], points[b]) {
                nets.join(a, i);
            }
        }
    }
    let mut named = HashMap::new();
    for (index, label) in &labels {
        if let Some(previous) = named.insert(label.to_ascii_lowercase(), *index) {
            nets.join(*index, previous);
        }
    }
    let mut names = HashMap::new();
    for (index, label) in &labels {
        let root = nets.root(*index);
        if let Some(previous) = names.insert(root, label.clone())
            && !previous.eq_ignore_ascii_case(label)
        {
            return Err(format!(
                "conflicting labels {previous:?} and {label:?} on the same net"
            ));
        }
    }
    let mut number = 1;
    for i in 0..points.len() {
        names.entry(nets.root(i)).or_insert_with(|| {
            loop {
                let name = format!("net{number}");
                number += 1;
                if !named.contains_key(&name) {
                    break name;
                }
            }
        });
    }
    let pin_names: Vec<_> = (0..points.len())
        .map(|i| names[&nets.root(i)].clone())
        .collect();
    if let Some(ports) = ports {
        let actual: HashSet<_> = components
            .iter()
            .filter(|c| matches!(c.kind(), "ipin" | "opin" | "iopin"))
            .filter_map(|c| c.value("lab"))
            .map(str::to_ascii_lowercase)
            .collect();
        let expected: HashSet<_> = ports.iter().map(|p| p.to_ascii_lowercase()).collect();
        if expected.len()!=ports.len() {return Err("duplicate hierarchy interface pin names".into());}
        if actual != expected {
            return Err(format!(
                "symbol pins {ports:?} do not match schematic ports {actual:?}"
            ));
        }
    }
    Ok(ResolvedSheet {
        components,
        pin_names,
    })
}

